"""The demo's two calls (fixtures/demo/demo_call_1.json and demo_call_2.json) as the dry run plays them.

Each line is either one of the user's recordings in fixtures/audio/ ("audio": "paint-08")
or speech generated by the realtime model ("audio": "voice"), in a voice per person, made
once and kept in runs/voices/ (the way tests/mouth/voices.py makes the proofs' voices). A
generated line is brought to the loudness of the recordings, so the line detector treats
both alike. A line's "then" is where Gawah should speak before the next line is said.
"""

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
DEMO = ROOT / "fixtures" / "demo"
AUDIO = ROOT / "fixtures" / "audio"
VOICES = ROOT / "runs" / "voices"  # git-ignored
SCREENSHOT = DEMO / "advance-5000.png"

# The demo's WhatsApp messages, as the run sheet has the user send them.
NUMBER_TEXT = "9000000002"  # the hirer sends the worker's number (the dry run's simulated worker)
SCREENSHOT_CAPTION = "Advance bhej diya"
WORK_DONE = "kaam poora ho gaya"
YES = "haan"


def call(no: int) -> dict:
    return json.loads((DEMO / f"demo_call_{no}.json").read_text())


def recorded(name: str) -> np.ndarray:
    import wave

    with wave.open(str(AUDIO / f"{name}.wav")) as w:
        assert (w.getframerate(), w.getnchannels(), w.getsampwidth()) == (16000, 1, 2)
        return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)


def _level(pcm: np.ndarray) -> float:
    """The loudness of the speech in a line: the 95th percentile of its sample sizes."""
    return float(np.percentile(np.abs(pcm.astype(np.float32)), 95)) or 1.0


def _recordings_level() -> float:
    names = sorted(p.stem for p in AUDIO.glob("paint-*.wav"))
    return float(np.median([_level(recorded(n)) for n in names]))


async def speech(lines: list[dict], openai_key: str | None) -> dict[int, tuple[bytes, int]]:
    """line_no -> (16-bit mono PCM, sample rate) for every line of a call."""
    from tests.mouth import voices

    target = _recordings_level()
    out: dict[int, tuple[bytes, int]] = {}
    for line in lines:
        if line["audio"] != "voice":
            out[line["line_no"]] = (recorded(line["audio"]).tobytes(), 16000)
            continue
        if openai_key is None:
            raise SystemExit("a generated line needs OPENAI_API_KEY")
        voice = voices.SUNITA if line["speaker"] == "hirer" else voices.RAMESH
        [pcm] = await voices.speak(openai_key, VOICES, [(voice, line.get("spoken", line["text"]))])
        samples = np.frombuffer(pcm, dtype=np.int16).astype(np.float32)
        scaled = np.clip(samples * (target / _level(samples.astype(np.int16))), -32768, 32767).astype(np.int16)
        out[line["line_no"]] = (scaled.tobytes(), 24000)
    return out
